const ORDER = [
  'reel-01-45-dney',
  'reel-08-6-sotok',
  'reel-09-pzz-uchastok',
  'reel-10-tyoplyi-pol',
  'udachnaya-02-vznos-100k',
  'reel-05-mify',
  'reel-12-usadka',
  'reel-13-paroizolyatsiya',
  'reel-14-otoplenie',
];

(async () => {
  for (const slug of ORDER) {
    const row = await getPipelineRow(slug);
    if (!row || !row.video_url) {
      console.error('SKIP', slug, '- no video_url in content_pipeline');
      continue;
    }
    const scheduledAt = await getNextYoutubeDailySlot();
    const id = await enqueuePost({
      reelSlug: slug,
      videoUrl: row.video_url,
      caption: YT_CAPTION[slug],
      scheduledAt,
      platform: 'youtube',
      contentTrack: 'main',
    });
    console.log('queued', slug, '-> scheduled_posts.id=' + id, 'at', scheduledAt.toISOString());
  }
})().catch((e) => {
  console.error('FATAL', e.message);
  process.exit(1);
});
